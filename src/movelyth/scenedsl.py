"""Scene DSL v1: bounded composition, beat resolution and layout budgets.

The director model writes :class:`movelyth.models.Scene` objects.  This module
turns them into render-ready dictionaries whose animation timings refer to the
*actual* TTS timeline, and rejects anything the Remotion renderer cannot draw
honestly.  Nothing here executes model-provided code.
"""
