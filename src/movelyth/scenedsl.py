def reserved_bands(orientation: str, layout: str) -> list[dict]:
    """Rects that content must not overlap."""
    caption_top, caption_bottom = CAPTION_BANDS[orientation]
    footer_top, footer_bottom = FOOTER_BANDS[orientation]
    width, height = (1920, 1080) if orientation == "landscape" else (1080, 1920)
    return [
        {"name": "标题区", **heading_band(orientation, layout)},
        {"name": "标签区", **label_band(orientation, layout)},
        {"name": "字幕区", "x": 0, "y": caption_top, "w": width, "h": caption_bottom - caption_top},
        {"name": "页脚区", "x": 0, "y": footer_top, "w": width, "h": footer_bottom - footer_top},
    ]


def _overlap(a: dict, b: dict) -> bool:
    return (a["x"] < b["x"] + b["w"] and b["x"] < a["x"] + a["w"]
            and a["y"] < b["y"] + b["h"] and b["y"] < a["y"] + a["h"])


