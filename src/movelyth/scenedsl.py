MIN_ACTION_FRACTION = 0.02

# Region boxes are the single source of truth shared with the renderer through
# studio/src/generated/layout.json (generated by ``write_renderer_contracts``).
# Non-reserved regions may overlap each other (e.g. an annotation over a chart),
