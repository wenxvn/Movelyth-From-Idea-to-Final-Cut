def _region_tuple(value: tuple[int, int, int, int]) -> dict[str, int]:
    x, y, width, height = value
    return {"x": x, "y": y, "w": width, "h": height}


def regions(orientation: str, layout: str) -> dict[str, dict[str, int]]:
    boxes = LAYOUTS[orientation].get(layout) or LAYOUTS[orientation]["diagram"]
    return {name: _region_tuple(box) for name, box in boxes.items()}


def heading_band(orientation: str, layout: str) -> dict[str, int]:
    bands = HEADING_BANDS[orientation]
    return _region_tuple(bands.get(layout) or bands["diagram"])


def label_band(orientation: str, layout: str) -> dict[str, int]:
    bands = LABEL_BANDS[orientation]
    return _region_tuple(bands.get(layout) or bands["diagram"])


def reserved_bands(orientation: str, layout: str) -> list[dict]:
    """Rects that content must not overlap."""
    caption_top, caption_bottom = CAPTION_BANDS[orientation]
    footer_top, footer_bottom = FOOTER_BANDS[orientation]
    width, height = (1920, 1080) if orientation == "landscape" else (1080, 1920)
    return [
        {"name": "标题区", **heading_band(orientation, layout)},
        {"name": "标签区", **label_band(orientation, layout)},
        {"name": "字幕区", "x": 0, "y": caption_top, "w": width, "h": caption_bottom - caption_top},
        {"name": "页脚区", "x": 0, "y": footer_top, "w": width, "h": footer_bottom - footer_top},
    ]


def _overlap(a: dict, b: dict) -> bool:
    return (a["x"] < b["x"] + b["w"] and b["x"] < a["x"] + a["w"]
            and a["y"] < b["y"] + b["h"] and b["y"] < a["y"] + a["h"])


def renderer_contract() -> dict:
    """Everything the TypeScript side must not re-invent."""
    return {
        "schema_version": SCHEMA_VERSION,
        "layouts": {orientation: {name: {key: _region_tuple(box) for key, box in boxes.items()}
                                  for name, boxes in variants.items()}
                    for orientation, variants in LAYOUTS.items()},
        "heading_bands": {orientation: {name: _region_tuple(box) for name, box in bands.items()}
                          for orientation, bands in HEADING_BANDS.items()},
        "label_bands": {orientation: {name: _region_tuple(box) for name, box in bands.items()}
                        for orientation, bands in LABEL_BANDS.items()},
        "caption_bands": {k: {"top": v[0], "bottom": v[1]} for k, v in CAPTION_BANDS.items()},
        "footer_bands": {k: {"top": v[0], "bottom": v[1]} for k, v in FOOTER_BANDS.items()},
        "safe_margin": SAFE_MARGIN,
        "layer_kinds": list(LayerKind.__args__),
        "procedural_kinds": list(VisualKind.__args__),
        "action_kinds": list(ActionKind.__args__),
        "layout_kinds": list(LayoutKind.__args__),
        "regions": list(Region.__args__),
    }


def write_renderer_contracts(studio_src: Path) -> list[Path]:
    """Write generated JSON consumed by the renderer; keep it reviewable in Git."""
    target = studio_src / "generated" / "layout.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(renderer_contract(), ensure_ascii=False, indent=2, sort_keys=True) + "\n",
                      encoding="utf-8")
    schema = studio_src / "generated" / "scene-schema.json"
    schema.write_text(json.dumps(Film.model_json_schema(), ensure_ascii=False, indent=2, sort_keys=True) + "\n",
                      encoding="utf-8")
    return [target, schema]


def char_timing(narration: str, boundaries: list[dict], duration: float):
    """Map a narration character index onto real TTS seconds."""
    spans, cursor = [], 0
    for boundary in boundaries or []:
        text = str(boundary.get("text") or "")
        if not text:
            continue
        start = narration.find(text, cursor)
        if start < 0:
            continue
        spans.append((start, start + len(text), float(boundary["start"]), float(boundary["end"])))
        cursor = start + len(text)

    def at(index: int) -> float:
        index = max(0, min(len(narration), index))
        for start, end, t0, t1 in spans:
            if start <= index < end:
                return t0 + (index - start) / max(1, end - start) * (t1 - t0)
        for start, _end, t0, _t1 in spans:
            if index < start:
                return t0
        return duration * index / max(1, len(narration))

    return at, ("tts-word-boundaries" if spans else "estimated-character-timing")


def resolve_time(spec: str, *, narration: str, at, duration: float) -> float:
    """Turn a DSL time reference into seconds inside this scene."""
    if spec == "start":
        return 0.0
    if spec == "end":
        return duration
    if spec.startswith("narration:"):
        fragment = spec.removeprefix("narration:")
        index = narration.find(fragment)
        if index < 0:
            raise ValueError(f"节拍片段“{fragment}”不在旁白中")
        return at(index)
    return float(spec) * duration


def resolve_actions(scene: Scene, duration: float, boundaries: list[dict] | None = None) -> list[dict]:
    """Resolve every action to a 0–1 fraction of the scene; reject invalid spans."""
    at, mode = char_timing(scene.narration, boundaries or [], max(1e-6, duration))
    layers = {layer.id for layer in scene.layers} or {"main"}
    resolved = []
    for action in scene.actions:
        if action.target not in layers:
            raise ValueError(f"镜头 {scene.id} 的动画目标 {action.target} 不存在")
        start = resolve_time(action.start, narration=scene.narration, at=at, duration=duration)
        end = resolve_time(action.end, narration=scene.narration, at=at, duration=duration)
        if not (math.isfinite(start) and math.isfinite(end)):
            raise ValueError(f"镜头 {scene.id} 的动画时间不是有限数")
        start = max(0.0, min(duration, start))
        end = max(0.0, min(duration, end))
        if end <= start:
            same = action.start == action.end
            raise ValueError(
                f"镜头 {scene.id} 的动画 {action.kind}（target={action.target}）"
                + (f"的 start 与 end 是同一个锚点「{action.start}」，解析后起止时间相同"
                   if same else
                   f"的 end「{action.end}」早于或等于 start「{action.start}」")
                + "；请让 end 指向旁白中更靠后的片段，或改用 start/end 与 0–1 小数")
        fraction = max(MIN_ACTION_FRACTION, (end - start) / max(1e-6, duration))
        resolved.append({"target": action.target, "kind": action.kind,
                         "from": round(start / max(1e-6, duration), 4),
                         "to": round(min(1.0, start / max(1e-6, duration) + fraction), 4),
                         "dx": action.dx, "dy": action.dy, "scale": action.scale,
                         "degrees": action.degrees})
    return resolved, mode


def default_layer(scene: Scene) -> Layer:
    return Layer(id="visual", type="procedural", region="main", procedural=scene.visual,
                 color=scene.color, emphasis=1)


def effective_layers(scene: Scene) -> list[Layer]:
    """Old tasks (``visual`` only) still render; new tasks may compose layers."""
    return list(scene.layers) or [default_layer(scene)]


def scene_signature(scene: Scene) -> str:
    """A coarse fingerprint of what is actually drawn, used for repetition checks."""
    parts = []
    for layer in effective_layers(scene):
        if layer.type == "procedural":
            parts.append(f"procedural:{layer.procedural}")
        elif layer.type == "chart":
            parts.append(f"chart:{layer.chart}:{len(layer.series)}:{len(layer.series[0].values) if layer.series else 0}")
        elif layer.type == "diagram":
            parts.append(f"diagram:{len(layer.nodes)}:{len(layer.edges)}")
        else:
            parts.append(f"{layer.type}:{layer.shape if layer.type == 'shape' else ''}")
    return "|".join(sorted(parts))


TEXT_BASE = {1: 30, 2: 36, 3: 44}
MATH_BASE = {1: 56, 2: 68, 3: 86}
MIN_FONT = {"text": 22, "math": 34}


# Math layers are drawn inside a padded surface box (studio/src/components/TextLayer.tsx
# uses padding 14px 20px), so the usable box is smaller than the region.
MATH_PADDING_Y = 28
MATH_PADDING_X = 40
LINE_HEIGHT = 1.42


def text_capacity(box: dict[str, int], font_size: int, *, single_line: bool = False,
                  math: bool = False) -> int:
    """Characters the box holds at *font_size*; ``single_line`` for formulas."""
    width = box["w"] - (MATH_PADDING_X if math else 0)
    height = box["h"] - (MATH_PADDING_Y if math else 0)
    per_line = max(1, int(width / (font_size * 1.02)))
    if single_line:
        # A single line must also fit the box height, or it is clipped rather than wrapped.
        return per_line if font_size * LINE_HEIGHT <= height else 0
    lines = max(1, int(height / (font_size * LINE_HEIGHT)))
    return per_line * lines


def layer_font(layer: Layer) -> tuple[int, int]:
    """Base font size and the smallest size the renderer will shrink to."""
    emphasis = max(1, min(3, layer.emphasis))
    if layer.type == "math":
        return MATH_BASE[emphasis], MIN_FONT["math"]
    return TEXT_BASE[emphasis], MIN_FONT["text"]


VISUAL_TYPES = {"chart", "diagram", "timeline", "procedural"}
# A scene must draw something; text/math alone is "a dynamic subtitle", not a visual.
DRAWING_TYPES = {"shape", "chart", "diagram", "timeline", "image", "procedural"}


def scene_visual_errors(scene: Scene) -> list[str]:
    layers = effective_layers(scene)
    if not any(layer.type in DRAWING_TYPES for layer in layers):
        return [f"镜头 {scene.id} 只有文字/公式，等于动态字幕，没有真正的画面；"
                f"至少加一个 shape/chart/diagram/timeline/image/procedural 图层"]
    return []


NODE_HEIGHT = 112
NODE_MIN_WIDTH = 210
# Each node box carries ~35 units of horizontal padding per side, so boxes that
# overlap by less than this never cover the label text they hold.
NODE_OVERLAP_TOLERANCE = 40


def node_width(label: str) -> int:
    """Mirror of the renderer's node box width (studio/src/components/DiagramLayer.tsx)."""
    return max(NODE_MIN_WIDTH, len(label) * 46 + 70)


def chart_semantic_errors(layer: Layer) -> list[str]:
    """Charts whose data cannot express what the narration claims.

    A bar chart with two series that are each constant (``[0,0]`` and ``[-2,-2]``)
    draws four bars where the narration compares two values, and the zero-height
    bar is invisible.  That is a data-shape error, not a styling preference.
    """
    if layer.chart != "bar" or len(layer.series) < 2:
        return []
    problems = []
    constant = [s for s in layer.series if len(set(s.values)) == 1]
    if len(constant) == len(layer.series):
        problems.append(
            f"柱状图 {layer.id} 的每个系列都是同一个常数值，无法表达对照；"
            f"要对比两个值请用**一个** series（values 放这两个值，x_values 放两个位置），"
            f"不同类别才用多个 series")
    if any(all(v == 0 for v in s.values) for s in layer.series):
        problems.append(f"柱状图 {layer.id} 有一个系列全是 0，等于没有数据；"
                        f"请把该值放进同一 series 的对照里，或改用折线")
    return problems


def diagram_node_overlaps(layer: Layer) -> list[str]:
    """Nodes that cover each other, so a label is drawn over by its neighbour.

    A real render showed '(-1)×(-1)=-1' clipped to '(-1)×(' because the next node
    started inside it.  The renderer draws nodes in order, so an overlap is always
    visible text loss, never a deliberate layer.

    Note that the SVG viewBox is computed from the nodes, so a node beyond 0–1000
    is *not* clipped — it only makes the whole diagram smaller.  That is a layout
    warning (:func:`diagram_scale_warning`), not a hard error.
    """
    problems = []
    boxes = []
    for node in layer.nodes:
        width = node_width(node.label)
        boxes.append((node, node.x - width / 2, node.x + width / 2, node.y - NODE_HEIGHT / 2,
                      node.y + NODE_HEIGHT / 2))
    for index, (first, left1, right1, top1, bottom1) in enumerate(boxes):
        for second, left2, right2, top2, bottom2 in boxes[index + 1:]:
            if left1 < right2 and left2 < right1 and top1 < bottom2 and top2 < bottom1:
                overlap = min(right1, right2) - max(left1, left2)
                if overlap <= NODE_OVERLAP_TOLERANCE:
                    continue
                problems.append(
                    f"图示节点 {first.id}「{first.label}」与 {second.id}「{second.label}」重叠 "
                    f"{overlap:.0f} 单位，后者会盖住前者的文字；请拉开 x（每个节点按标签长度约占 "
                    f"{node_width(first.label)} 单位）或改成不同 y 分行")
    return problems


def diagram_scale_warning(layer: Layer) -> str | None:
    """The diagram is much wider than the 1000-unit design space, so it renders small."""
    span = max((node.x + node_width(node.label) / 2 for node in layer.nodes), default=0) - \
        min((node.x - node_width(node.label) / 2 for node in layer.nodes), default=0)
    if span > 1300:
        return (f"图示内容宽约 {span:.0f} 单位（设计空间 1000），会整体缩小约 "
                f"{1000 / span:.0%}；建议缩短节点标签或减少并排节点")
    return None


def layout_errors(scene: Scene, *, vertical: bool) -> list[str]:
    """Hard errors: unrenderable placement, overlap, or text that cannot fit at all."""
    orientation = "portrait" if vertical else "landscape"
    boxes = regions(orientation, scene.layout)
    reserved = reserved_bands(orientation, scene.layout)
    errors: list[str] = scene_visual_errors(scene)
    used: list[tuple[str, dict]] = []
    for layer in effective_layers(scene):
        box = boxes.get(layer.region)
        if box is None:
            errors.append(f"镜头 {scene.id}: 未知区域 {layer.region}")
            continue
        if layer.region == "full":
            continue
        if layer.type == "diagram":
            errors.extend(f"镜头 {scene.id} 的 {layer.id}：{problem}"
                          for problem in diagram_node_overlaps(layer))
        if layer.type == "chart":
            errors.extend(f"镜头 {scene.id} 的 {problem}" for problem in chart_semantic_errors(layer))
        if layer.type in VISUAL_TYPES and layer.region not in {"main", "full", "side"}:
            errors.append(
                f"镜头 {scene.id} 的 {layer.id}（{layer.type}）放在 {layer.region} 会缩得太小；"
                f"图表/图示/时间线/程序动画请放在 main，或用 layout=compare 的 main/side")
        if layer.type in VISUAL_TYPES and layer.region == "side" and scene.layout != "compare":
            errors.append(f"镜头 {scene.id} 的 {layer.id}（{layer.type}）在 {scene.layout} 布局里不能用 side，"
                          f"请改用 main 或 layout=compare")
        for band in reserved:
            if _overlap(box, band):
                errors.append(f"镜头 {scene.id} 的 {layer.id} 与{band['name']}重叠")
        for other_id, other in used:
            if _overlap(box, other):
                errors.append(f"镜头 {scene.id} 的 {layer.id} 与 {other_id} 在同一区域互相遮挡")
        used.append((layer.id, box))
        if layer.text:
            _base, minimum = layer_font(layer)
            math = layer.type == "math"
            capacity = text_capacity(box, minimum, math=math)
            if len(layer.text) > capacity:
                hint = ("；公式太长时请移到 main，或拆成两行并压缩字数"
                        if math else "")
                errors.append(
                    f"镜头 {scene.id} 的 {layer.id} 文本 {len(layer.text)} 字超出"
                    f"{layer.region} 区域的最小字号容量 {capacity} 字{hint}")
            if formula_is_one_line(layer) and len(layer.text) > text_capacity(
                    box, minimum, single_line=True, math=True):
                errors.append(
                    f"镜头 {scene.id} 的 {layer.id} 公式在 {layer.region} 区域放不下："
                    f"缩到最小字号 {minimum}px 仍会折行或被裁切；"
                    f"请缩短公式、改写成多行（用 \\n），或移到更大的区域")
    return errors


def formula_is_one_line(layer: Layer) -> bool:
    """A math layer is one expression unless the director wrote explicit rows."""
    return layer.type == "math" and "\n" not in layer.text


def layout_warnings(scene: Scene, *, vertical: bool) -> list[str]:
    """Soft warnings: text will be shrunk, or the layout may look crowded."""
    orientation = "portrait" if vertical else "landscape"
    boxes = regions(orientation, scene.layout)
    warnings = []
    for layer in effective_layers(scene):
        box = boxes.get(layer.region) or boxes["main"]
        base, minimum = layer_font(layer)
        capacity = text_capacity(box, base, single_line=formula_is_one_line(layer),
                                 math=layer.type == "math")
        if layer.text and len(layer.text) > capacity:
            warnings.append(f"镜头 {scene.id} 的 {layer.id} 文本 {len(layer.text)} 字超出"
                            f"约 {capacity} 字容量，渲染时会缩到 {minimum}px 以内")
        if layer.type == "diagram" and len(layer.steps) > 5:
            warnings.append(f"镜头 {scene.id} 的 {layer.id} 步骤过多，竖版可能拥挤")
        if layer.type == "diagram" and layer.steps and any(node.y > 420 for node in layer.nodes):
            warnings.append(f"镜头 {scene.id} 的 {layer.id} 节点与步骤列表可能重叠，建议节点 y ≤ 420")
        if layer.type == "diagram":
            scale = diagram_scale_warning(layer)
            if scale:
                warnings.append(f"镜头 {scene.id} 的 {layer.id}：{scale}")
        if layer.type == "chart" and any(len(s.values) > 24 for s in layer.series):
            warnings.append(f"镜头 {scene.id} 的 {layer.id} 数据点超过 24 个，标注会拥挤")
        if layer.type == "text" and layer.text:
            # Estimate the same breaks the renderer will make and report what a viewer notices.
            base, _minimum = layer_font(layer)
            per_line = max(1, int(box["w"] / (base * 1.02)))
            for issue in typography_issues(wrap(layer.text, per_line), per_line):
                warnings.append(f"镜头 {scene.id} 的 {layer.id} 中文排版：{issue}")
    for action in scene.actions:
        if action.kind == "morph":
            warnings.append(f"镜头 {scene.id} 的 morph 以淡入实现，不是真正的形状插值")
    return warnings


def resolve_beats(scene: Scene, duration: float, boundaries: list[dict] | None = None) -> list[dict]:
    at, _mode = char_timing(scene.narration, boundaries or [], max(1e-6, duration))
    resolved = []
    for beat in scene.beats:
        seconds = resolve_time(beat.at, narration=scene.narration, at=at, duration=duration)
        if not math.isfinite(seconds):
            raise ValueError(f"镜头 {scene.id} 的节拍时间无效")
        resolved.append({"at": round(max(0.0, min(duration, seconds)), 3),
                         "fraction": round(max(0.0, min(1.0, seconds / max(1e-6, duration))), 4),
                         "purpose": beat.purpose})
    return sorted(resolved, key=lambda item: item["at"])


def normalize_scene(scene: Scene, *, duration: float, boundaries: list[dict] | None = None,
                    vertical: bool = False) -> dict:
    """Return the render-ready scene dict.  Raises on anything unrenderable."""
    if not math.isfinite(duration) or duration <= 0:
        raise ValueError(f"镜头 {scene.id} 时长无效")
    layers = effective_layers(scene)
    actions, timing_mode = resolve_actions(Scene.model_validate(scene.model_dump()), duration, boundaries)
    beats = resolve_beats(scene, duration, boundaries)
    warnings = layout_warnings(scene, vertical=vertical)
    data = scene.model_dump()
    data.update({
        "schema_version": SCHEMA_VERSION,
        "layers": [layer.model_dump() for layer in layers],
        "actions_resolved": actions,
        "beat_times": beats,
        "beat_timing": timing_mode,
        "layout_warnings": warnings,
        "duration": round(duration, 3),
    })
    return data


def validate_cut_timeline(cut: dict, fps: int) -> list[str]:
    """Consistency checks over a prepared cut (frames, captions, actions)."""
    problems = []
    total = 0
    for scene in cut["scenes"]:
        frames = scene["frames"]
        if not isinstance(frames, int) or frames <= 0:
            problems.append(f"{scene['id']}: 帧数无效")
            continue
        seconds = frames / fps
        previous_end = 0.0
        for page in scene.get("captions", []):
            if not 0 <= page["start"] < page["end"] <= seconds + 1e-6:
                problems.append(f"{scene['id']}: 字幕时间越界")
            if page["start"] < previous_end - 1e-6:
                problems.append(f"{scene['id']}: 字幕交叠")
            previous_end = page["end"]
        for action in scene.get("actions_resolved", []):
            if not 0 <= action["from"] < action["to"] <= 1.0:
                problems.append(f"{scene['id']}: 动画区间越界")
        total += frames
    if total <= 0:
        problems.append("总帧数为 0")
    return problems


def validate_cut_dsl(cut: Cut, *, vertical: bool) -> list[str]:
    """Pre-render contract checks shared by script review and rendering."""
    problems = []
    for scene in cut.scenes:
        problems.extend(layout_errors(scene, vertical=vertical))
        # Resolve against an estimated duration so bad references fail early.
        # Beats must be resolved too: a narration: fragment that is not in the
        # narration would otherwise only fail after TTS has been paid for.
        try:
            resolve_actions(scene, duration=10.0, boundaries=[])
        except ValueError as exc:
            problems.append(str(exc))
        try:
            resolve_beats(scene, duration=10.0, boundaries=[])
        except ValueError as exc:
            problems.append(str(exc))
    return problems

MAX_DATA_BYTES = 256_000
DATA_SUFFIXES = (".json", ".csv")


def resolve_data_file(data_dir: Path, data_ref: str) -> Path:
    """Only a bounded identifier inside the task's data directory."""
    base = data_dir.resolve()
    for suffix in DATA_SUFFIXES:
        candidate = (base / f"{data_ref}{suffix}").resolve()
        if candidate.is_relative_to(base) and candidate.is_file():
            return candidate
    return base / f"{data_ref}.json"


def _load_csv(path: Path) -> tuple[list[dict], str, str]:
    """Read a numeric CSV: either one column of values or a header of series columns."""
    import csv

    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.reader(stream))
    rows = [row for row in rows if any(cell.strip() for cell in row)]
    if not rows:
        raise ValueError("CSV 为空")
    header = rows[0]
    try:
        [float(cell) for cell in header if cell.strip()]
        numeric_header = True
    except ValueError:
        numeric_header = False
    series = []
    if numeric_header:
        values = [float(cell) for row in rows for cell in row if cell.strip()]
        series.append({"label": path.stem, "values": values, "unit": ""})
        unit = axis = ""
    else:
        labels = [cell.strip() or f"列{i + 1}" for i, cell in enumerate(header)]
        columns: list[list[float]] = [[] for _ in labels]
        for row in rows[1:]:
            for index in range(min(len(labels), len(row))):
                cell = row[index].strip()
                if cell:
                    columns[index].append(float(cell))
        for label, values in zip(labels, columns):
            if values:
                series.append({"label": label[:16], "values": values, "unit": ""})
        unit = axis = ""
    if not series:
        raise ValueError("CSV 没有可用的数值列")
    for entry in series:
        if not 2 <= len(entry["values"]) <= 60 or any(not math.isfinite(v) for v in entry["values"]):
            raise ValueError("CSV 序列需为 2–60 个有限数")
    return series[:4], unit, axis


def load_series(path: Path) -> tuple[list[dict], str, str]:
    """Read a bounded local JSON or CSV data file (never a URL or a script)."""
    from .util import read_json

    if not path.is_file():
        raise ValueError(f"数据文件不存在：{path.name}")
    if path.stat().st_size > MAX_DATA_BYTES:
        raise ValueError(f"数据文件超过 {MAX_DATA_BYTES} 字节上限")
    if path.suffix.lower() == ".csv":
        return _load_csv(path)
    data = read_json(path)
    if isinstance(data, list):
        entries = [{"label": path.stem, "values": data}]
    elif isinstance(data, dict) and isinstance(data.get("series"), list):
        entries = data["series"]
    elif isinstance(data, dict) and isinstance(data.get("values"), list):
        entries = [data]
    else:
        raise ValueError("数据文件需为数值数组或包含 values/series 的对象")
    series = []
    for entry in entries[:4]:
        if not isinstance(entry, dict) or not isinstance(entry.get("values"), list):
            raise ValueError("数据序列格式无效")
        values = entry["values"]
        if not 2 <= len(values) <= 60 or any(not isinstance(v, (int, float)) or not math.isfinite(v)
                                             for v in values):
            raise ValueError("数据序列需为 2–60 个有限数")
        series.append({"label": str(entry.get("label") or path.stem)[:16], "values": [float(v) for v in values],
                       "unit": str(entry.get("unit") or "")[:8]})
    unit = str(data.get("unit") or "")[:8] if isinstance(data, dict) else ""
    axis = str(data.get("axis") or "")[:16] if isinstance(data, dict) else ""
    return series, unit, axis


def resolve_data_layers(scenes: list[dict], data_dir: Path, assets: list[str]) -> list[dict]:
    """Bind chart/image layers to bounded local data or fail before rendering."""
    for scene in scenes:
        for layer in scene.get("layers", []):
            if layer["type"] == "chart" and not layer["series"] and layer["data_ref"]:
                series, unit, axis = load_series(resolve_data_file(data_dir, layer["data_ref"]))
                layer["series"] = series
                layer["unit"] = layer["unit"] or unit
                layer["axis"] = layer["axis"] or axis
                layer["source_note"] = layer["source_note"] or f"本地数据 · {layer['data_ref']}"
            if layer["type"] == "image":
                dashed = layer["data_ref"].replace("_", "-")
                candidates = (dashed, f"asset-{layer['data_ref']}")
                if not any(name.startswith(candidates) for name in assets):
                    raise ValueError(f"镜头 {scene['id']} 的图片素材 {layer['data_ref']} 不在受控素材目录")
            if layer["type"] == "chart" and not layer["series"]:
                raise ValueError(f"镜头 {scene['id']} 的图表 {layer['id']} 没有数据")
    return scenes
